"""Generate synthetic acceptance scenes through the real queue and signed-in Codex provider.

The account supplies credentials only. Sources and queue state live in an explicitly
separate work directory; no production recordings or illustration database are used.
"""
import argparse
import datetime as dt
import hashlib
import io
import json
import os
from pathlib import Path
import sys
import time
import uuid
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / 'Apps/MacApp/Context'), str(ROOT / 'Apps/MacApp/Runtime'),
                str(ROOT / 'Vendor/HermesAgent')]
from context_store import ContextStore, digest
from life_illustrations import LifeIllustrations
from life_illustration_generator import CodexIllustrationGenerator, parse_scene_output
from PIL import Image

SCENES = {
    'code': '我们现在坐在桌边讨论代码里两个模块的数据怎样交接。桌上放着两组积木，我把一块积木挪到两组中间，同伴用手指着还没连上的缺口。我们正在试着说明接口边界，方案还没有定，也没有动手修完代码。',
    'outdoor': '刚才慢慢走了一会儿，现在我们两个人停下脚步。我蹲下来，指给同伴看脚边的一片叶子：叶缘缺了一小块，叶脉很清楚。同伴也弯下腰凑近看，手掌摊开放在旁边作比较。我们还在观察，没有把叶子摘走，也没有决定接下来去哪里。',
    'night': '我现在坐在桌边喝茶，桌上摊着一本画册。我一只手握着小茶杯，另一只手刚刚捏住一页的角，还没有翻过去。画册里是一笔山的轮廓，没有字。杯口还有一点热气。我打算看完这一页就休息，还没有收起画册。',
}

STOPS = [
    ('望京工作室', 39.9982, 116.4796, 6.1, 8.7),
    ('亮马河畔步道', 39.9478, 116.4638, 9.2, 11.5),
    ('东四胡同书房', 39.9316, 116.4184, 12.1, 15.0),
]


def journey_records(day_start):
    records = [dict(id=f'visit-{index}', source_name='CoreLocation visits', title=title,
        latitude=latitude, longitude=longitude, start=day_start + arrival * 3600,
        end=day_start + departure * 3600, accuracy=25)
        for index, (title, latitude, longitude, arrival, departure) in enumerate(STOPS)]
    for index, (latitude, longitude, hour) in enumerate([(39.9685, 116.4660, 8.95), (39.9395, 116.4380, 11.8)]):
        records.append(dict(id=f'waypoint-{index}', source_name='CoreLocation significant_change',
            latitude=latitude, longitude=longitude, start=day_start + hour * 3600,
            end=day_start + hour * 3600, accuracy=80))
    return records


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--account', type=Path, required=True)
    parser.add_argument('--work', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--reuse-images', action='store_true', help='Extract fresh Codex summaries and retain the existing PNG bytes')
    args = parser.parse_args()
    if args.work.resolve() == args.account.resolve():
        raise ValueError('Acceptance work must be isolated from the account directory')
    os.environ['TZ'] = 'Asia/Shanghai'
    time.tzset()
    args.output.mkdir(parents=True, exist_ok=True)
    generator = CodexIllustrationGenerator(args.account)
    llm = generator.resolve()
    evidence = dict(disclosure='Invented acceptance fixtures, not real user events. PNGs generated by the real signed-in Codex subscription through LifeIllustrations + CodexIllustrationGenerator.',
                    model=llm['model_id'], original_size='1024x1024', output_size='1024x1024',
                    thumbnail_size='512x512', background='transparent, warm-ivory kiss-cut paper rim', samples={})
    if args.reuse_images:
        evidence['disclosure'] = 'Invented acceptance fixtures. Existing real Codex sticker PNG bytes reused unchanged; summaries freshly extracted by the signed-in Codex provider from synthetic transcripts and visits.'
    reference = ROOT / 'Apps/MacApp/Runtime/momo_character_reference.png'
    evidence['reference_sha256'] = hashlib.sha256(reference.read_bytes()).hexdigest()
    start = dt.datetime(2026, 11, 5, 14, tzinfo=ZoneInfo('Asia/Shanghai')).timestamp()
    context = ContextStore(args.work / 'context')
    queue = LifeIllustrations(args.work)
    try:
        queue.update_settings({'enabled': True}, generator.availability(), start + 1)
        context.db.execute('INSERT OR REPLACE INTO phone_source_snapshots VALUES(?,?,?,?,?)',
            ('fixture-device', 'visits', 1, json.dumps(dict(state='enabled', window_start=start - 6 * 3600,
                window_end=start + 10 * 3600, records=journey_records(start - 6 * 3600))), start))
        for index, (name, text) in enumerate(SCENES.items()):
            timestamp = start + index * 10800 + 60
            context.sync_source(dict(library_id=str(uuid.uuid5(uuid.NAMESPACE_URL, 'momo-art-acceptance')),
                session_id=str(uuid.uuid5(uuid.NAMESPACE_URL, 'momo-art-acceptance-' + name)),
                device_id=str(uuid.uuid5(uuid.NAMESPACE_URL, 'momo-art-fixture-device')),
                generation=0, version=1, deleted=False, recorded_at=timestamp,
                spans=[dict(id=str(uuid.uuid5(uuid.NAMESPACE_URL, 'momo-art-span-' + name)),
                            recorded_at=timestamp, text=text)], text_sha256=digest(text)))
        now = start + 9 * 3600 + 600
        queue.scan(context, now)
        for name in SCENES:
            print('Generating ' + name, flush=True)
            before = time.monotonic()
            if args.reuse_images:
                row = queue.db.execute('SELECT * FROM slots ORDER BY window_start LIMIT 1 OFFSET ?', (list(SCENES).index(name),)).fetchone()
                summary, brief = parse_scene_output(generator.prepare(json.loads(row['evidence'])))
                if brief == 'SKIP':
                    raise ValueError('Expected a grounded scene for the explicit acceptance fixture')
                data = (args.output / f'sample_{name}.png').read_bytes()
                thumbnail = (args.output / f'sample_{name}_thumbnail.png').read_bytes()
                hashes = [hashlib.sha256(raw).hexdigest() for raw in (data, thumbnail)]
                for sha, raw in zip(hashes, (data, thumbnail)):
                    (queue.assets / (sha + '.png')).write_bytes(raw)
                queue.db.execute("UPDATE slots SET state='ready',summary=?,brief=?,asset_sha256=?,thumbnail_sha256=?,width=1024,height=1024 WHERE id=?",
                    (summary, brief, *hashes, row['id']))
                queue.publish(queue.db.execute('SELECT * FROM slots WHERE id=?', (row['id'],)).fetchone())
            else:
                queue.advance(generator, context, now)
            row = queue.db.execute('SELECT * FROM slots ORDER BY window_start LIMIT 1 OFFSET ?',
                                   (list(SCENES).index(name),)).fetchone()
            if row['state'] != 'ready':
                raise RuntimeError(f"{name}: {row['state']} / {row['error']}; do not blindly retry an unknown image outcome")
            data = queue.asset(row['asset_sha256'])
            thumbnail = queue.asset(row['thumbnail_sha256'])
            (args.output / f'sample_{name}.png').write_bytes(data)
            (args.output / f'sample_{name}_thumbnail.png').write_bytes(thumbnail)
            with Image.open(io.BytesIO(data)) as image:
                assert image.mode in ('RGB', 'RGBA') and image.size == (1024, 1024)
                assert image.mode == 'RGBA' and image.getchannel('A').getextrema() == (0, 255)
                assert all(image.getpixel(point)[3] == 0 for point in [(0, 0), (1023, 0), (0, 1023), (1023, 1023)])
                assert any(low < high for low, high in image.convert('RGB').getextrema())
                pixels = dict(mode=image.mode, channel_extrema=image.getextrema(),
                              corner_rgb=image.convert('RGB').getpixel((0, 0)))
            evidence['samples'][name] = dict(source=SCENES[name], brief=row['brief'],
                summary=row['summary'], reused_images=args.reuse_images,
                response_id=row['response_id'], request_id=row['request_id'], attempt=row['attempt'],
                asset_sha256=row['asset_sha256'], thumbnail_sha256=row['thumbnail_sha256'],
                elapsed_seconds=round(time.monotonic() - before, 2), **pixels)
            evidence['manifest'] = queue.manifest()
            filename = 'journey_generation_evidence.json' if args.reuse_images else 'generation_evidence.json'
            (args.output / filename).write_text(json.dumps(evidence, ensure_ascii=False, indent=2) + '\n')
            print(name + ': ready kiss-cut sticker', flush=True)
    finally:
        queue.close()
        context.close()


if __name__ == '__main__':
    main()
